/* ================================================
   PATTERN ANALYSIS
   ================================================ */
function analyzePattern(cards) {
  const pattern = cards.map(c => c.choiceLabel).join('');
  const aCount = cards.filter(c => c.choiceLabel === 'A').length;
  const bCount = cards.filter(c => c.choiceLabel === 'B').length;

  let maxAStreak = 0, maxBStreak = 0;
  let curA = 0, curB = 0;
  for (const c of cards) {
    if (c.choiceLabel === 'A') { curA++; curB = 0; maxAStreak = Math.max(maxAStreak, curA); }
    else { curB++; curA = 0; maxBStreak = Math.max(maxBStreak, curB); }
  }

  const isAlternating = pattern === 'ABABABABAB' || pattern === 'BABABABABA';
  const isClustered = maxAStreak >= 5 || maxBStreak >= 5;

  return {
    pattern,
    aCount,
    bCount,
    maxAStreak,
    maxBStreak,
    isAlternating,
    isClustered,
    dominantChoice: aCount > bCount ? 'A' : (bCount > aCount ? 'B' : 'balanced')
  };
}

