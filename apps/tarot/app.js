/* ================================================
   NARRATIVE GENERATION — returns 4 separate sections
   ================================================ */
function generateNarrative(category, cardIdx, cards) {
  const score = cards.reduce((s, c) => s + (c.choiceLabel === 'A' ? 0 : 1), 0);
  const outcomeIdx = scoreToOutcomeIndex(score);
  const nd = narrativeData[category][outcomeIdx];
  const recommended = `<strong>${deck[cardIdx].name}</strong>`;

  return `
    <div class="narrative-row narrative-recommended">
      <span class="narrative-text">ไพ่ประจำตัวของคุณ ก็คือ  ${recommended}</span>
    </div>
    <div class="narrative-row narrative-meaning">
      <span class="narrative-text">${nd.meaning}</span>
    </div>
    <div class="narrative-row narrative-pros">
      <span class="narrative-text">${nd.pros}</span>
    </div>
    <div class="narrative-row narrative-cons">
      <span class="narrative-text">${nd.cons}</span>
    </div>
  `;
}

/* ================================================
   STATE
   ================================================ */
let currentCategory = null;
let currentQ = 0;
let drawnCards = []; // { choiceLabel: 'A'|'B', questionText }
let donationState = null; // 'A'|'B'|'C'|'D'|null

/* ================================================
   DOM HELPERS
   ================================================ */
const $ = id => document.getElementById(id);

const screenSelect   = $('screen-select');
const screenQuestion = $('screen-question');
const screenSummary  = $('screen-summary');

/* ================================================
   SCREEN TRANSITIONS
   ================================================ */
function showScreen(name) {
  [screenSelect, screenQuestion, screenSummary]
    .forEach(s => s.classList.add('hidden'));
  const el = ({ select: screenSelect, question: screenQuestion, summary: screenSummary })[name];
  if (!el) return;
  el.classList.remove('hidden');
  el.style.animation = 'none';
  el.offsetHeight;
  el.style.animation = '';
}

/* ================================================
   STARS BACKGROUND
   ================================================ */
function initStars() {
  const container = $('stars');
  if (container.children.length > 0) return;
  for (let i = 0; i < 80; i++) {
    const star = document.createElement('div');
    star.className = 'star';
    star.style.left   = Math.random() * 100 + '%';
    star.style.top    = Math.random() * 100 + '%';
    star.style.setProperty('--dur',   (2 + Math.random() * 4) + 's');
    star.style.setProperty('--delay', Math.random() * 5 + 's');
    container.appendChild(star);
  }
}

/* ================================================
   CATEGORY SELECTION
   ================================================ */
$('category-grid').addEventListener('click', e => {
  const btn = e.target.closest('.category-card');
  if (!btn) return;
  startReading(btn.dataset.cat);
});

function startReading(cat) {
  currentCategory = cat;
  currentQ = 0;
  drawnCards = [];
  $('category-badge').textContent = cat;
  showScreen('question');
  loadQuestion();
}

/* ================================================
   LOAD QUESTION
   ================================================ */
function loadQuestion() {
  const cats = categories();
  const qs = cats[currentCategory].questions;
  const q = qs[currentQ];

  $('question-number').textContent = `คำถามที่ ${currentQ + 1}`;
  $('question-text').textContent = q.text;
  $('question-context').textContent = q.context;

  const progress = (currentQ / 10) * 100;
  $('progress-bar').style.width = progress + '%';
  $('progress-label').textContent = `คำถามที่ ${currentQ + 1} / 10`;

  const elA = $('choice-a');
  const elB = $('choice-b');

  elA.innerHTML = `
    <span class="choice-label">เลือก A</span>
    <span class="choice-path">${q.A.path}</span>
    <span class="choice-trade">${q.A.trade}</span>
  `;
  elB.innerHTML = `
    <span class="choice-label">เลือก B</span>
    <span class="choice-path">${q.B.path}</span>
    <span class="choice-trade">${q.B.trade}</span>
  `;

  elA.onclick = () => selectChoice('A', q);
  elB.onclick = () => selectChoice('B', q);
}

/* ================================================
   SELECT CHOICE
   A = 0 pts  |  B = 1 pt
   ================================================ */
function selectChoice(choice, question) {
  drawnCards.push({
    choiceLabel: choice,
    questionText: question.text
  });

  currentQ++;

  if (currentQ >= 10) {
    $('progress-bar').style.width = '100%';
    $('progress-label').textContent = `คำถามที่ 10 / 10`;
    setTimeout(() => showSummary(), 400);
  } else {
    loadQuestion();
  }
}

/* ================================================
   SUMMARY — SINGLE CARD REVEAL + DONATION FLOW
   ================================================ */
function showSummary() {
  const cats = categories();
  const cat = cats[currentCategory];

  const score = drawnCards.reduce((s, c) => s + (c.choiceLabel === 'A' ? 0 : 1), 0);
  const outcomeIdx = scoreToOutcomeIndex(score);
  const cardIdx = cat.outcomes[outcomeIdx];
  const isSad = outcomeIdx === 0;

  showScreen('summary');

  $('summary-category-label').textContent = `ผลลัพธ์ในหมวด ${currentCategory}`;

  // Trigger card reveal animation
  const wrap = $('card-interaction-area');
  wrap.classList.remove('revealed', 'flipped');
  void wrap.offsetWidth; // reflow

  const img = $('summary-card-img');
  img.src = `assets/cards/card-${String(cardIdx).padStart(2, '0')}.png`;

  setTimeout(() => wrap.classList.add('revealed'), 150);

  $('summary-card-name').textContent = deck[cardIdx].name;

  $('summary-narrative').innerHTML = generateNarrative(currentCategory, cardIdx, drawnCards);

  // Reset card faces to front, hide save button
  $('card-front').classList.remove('flipped');
  $('card-back').classList.remove('flipped');
  $('card-back').classList.add('hidden');
  $('card-front').classList.remove('hidden');
  const saveWrap = $('save-btn-wrap');
  if (saveWrap) saveWrap.classList.add('hidden');

  if (isSad) {
    donationState = 'A';
    // Wire tap on card area to flip to QR
    $('card-interaction-area').onclick = onCardTap;
  } else {
    donationState = null;
    $('card-interaction-area').style.cursor = 'default';
    $('card-interaction-area').onclick = null;
  }
}

/* ================================================
   DONATION STATE MACHINE
   State A: sad card front — tap → flip to QR back (State B)
   State B: QR back visible — tap QR → show save button (State C)
   State C: save button visible — tap Save → show happy card (State D)
   State B/C: tap "ไม่สะดวกโอน" → resetToHome()
   ================================================ */

function onCardTap() {
  if (donationState !== 'A') return;
  // Flip card to QR back
  $('card-front').classList.add('flipped');
  $('card-back').classList.remove('hidden');
  void $('card-back').offsetWidth;
  $('card-back').classList.add('flipped');

  donationState = 'B';
  $('card-interaction-area').onclick = null;
  $('qr-wrap').onclick = onQRTap;
  $('skip-link').onclick = resetToHome;
}

function onQRTap() {
  if (donationState !== 'B') return;
  // Show save button
  $('save-btn-wrap').classList.remove('hidden');
  donationState = 'C';
  $('qr-wrap').onclick = null;
  $('save-qr-btn').onclick = onSaveTap;
  // skip-link stays wired
}

function onSaveTap() {
  if (donationState !== 'C') return;
  // Replace QR content with happy card + thank-you message
  $('qr-info-wrap').innerHTML = `
    <img id="happy-final-img" src="assets/happy/card-03.png" alt="ไพ่ทาโร่ต์มงคล" />
    <div class="happy-thanks-heading">ขอบคุณที่สนับสนุน! ✨</div>
    <div class="happy-thanks-sub">
      พลังบวกได้รับการส่งต่อแล้ว<br />
      ให้พลังนั้นนำทางคุณไปต่อ 💛
    </div>
  `;
  donationState = 'D';
  $('skip-link').onclick = null;
  $('save-qr-btn').onclick = null;
}

function resetToHome() {
  currentCategory = null;
  currentQ = 0;
  drawnCards = [];
  donationState = null;
  showScreen('select');
}

/* ================================================
   RESTART
   ================================================ */
$('restart-btn').addEventListener('click', resetToHome);

